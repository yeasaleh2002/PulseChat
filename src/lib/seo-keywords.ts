export function getKeywordCount(): number {
  return Object.values(SEO_KEYWORD_CATEGORIES).reduce(
    (total, category) => total + category.length,
    0
  );
}

export function getAllKeywordsFlat(): string[] {
  return Array.from(
    new Set(Object.values(SEO_KEYWORD_CATEGORIES).flat())
  );
}

export function getRandomKeywords(
  count: number = 15,
  categories?: (keyof typeof SEO_KEYWORD_CATEGORIES)[]
): string[] {
  const selectedCategories = categories
    ? categories.flatMap((cat) => SEO_KEYWORD_CATEGORIES[cat] || [])
    : getAllKeywordsFlat();

  const shuffled = [...selectedCategories].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

export function getContextualKeywords(route: string): string[] {
  switch (route) {
    case "/chat":
      return getRandomKeywords(15, [
        "realTimeChat",
        "websocketsSocketIo",
        "scalableFrontend",
        "groupCollaboration",
        "secureMessaging"
      ]);
    case "/login":
      return getRandomKeywords(12, [
        "secureMessaging",
        "realTimeChat",
        "enterpriseTechStack"
      ]);
    default:
      return getRandomKeywords(15, [
        "realTimeChat",
        "nextjsArchitecture",
        "productivityTools",
        "uiUxDesign",
        "enterpriseTechStack"
      ]);
  }
}
